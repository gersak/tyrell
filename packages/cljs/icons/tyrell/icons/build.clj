(ns tyrell.icons.build
  "Copy only the icons your code uses out of the tyrell icon sets.

   The sets are ~10 MB of defs. A ClojureScript :advanced build drops the
   unused ones; the JVM has no such pass, so this does it ahead of time:
   find the icon vars your code uses (clj-kondo's analysis), then write trimmed
   copies of the same namespaces to :out. Put :out on the production
   classpath instead of the icon jars. Requires and call sites stay as they
   are.

   deps.edn:

     {:paths [\"src\" \"resources\"]
      :aliases
      {:dev   {:extra-deps {dev.gersak/tyrell-icons {:mvn/version \"…\"}}}
       :prod  {:extra-paths [\"gen-icons\"]}
       :icons {:extra-deps {dev.gersak/tyrell-icons {:mvn/version \"…\"}
                            clj-kondo/clj-kondo {:mvn/version \"2026.08.04\"}}
               :exec-fn tyrell.icons.build/extract
               :exec-args {:paths [\"src\"] :out \"gen-icons\"}}}}

     clj -X:icons

   Keep :out off the :dev classpath: the trimmed copies use the same
   namespace names, so whichever comes first wins.

   Options:
     :paths      source dirs to analyze. Default [\"src\"].
     :out        where the trimmed namespaces go. Default \"gen-icons\".
     :include    extra icons the scan can't see, e.g. names built at runtime:
                 [tyrell.lucide/heart tyrell.heroicons.outline/user].
     :svg-dir    also write each icon as a file, <svg-dir>/lucide/mail.svg,
                 for template engines that include files.
     :registry   a var holding your name -> SVG map, e.g. app.icons/registry:
                   (def registry {:mail lucide/mail :action-down lucide/chevron-down})
     :js-out     with :registry, write it as a static script that registers
                 those names, e.g. \"resources/public/icons.js\". Serve it
                 with long cache headers and load it right after tyrell.js;
                 templates then use <ty-icon name=\"mail\">."
  (:require [clojure.java.io :as io]
            [clojure.string :as str]))

(def icon-namespaces
  '[tyrell.lucide
    tyrell.heroicons.outline tyrell.heroicons.solid tyrell.heroicons.mini tyrell.heroicons.micro
    tyrell.material.filled tyrell.material.outlined tyrell.material.round
    tyrell.material.sharp tyrell.material.two-tone
    tyrell.fav6.solid tyrell.fav6.regular tyrell.fav6.brands])

(def ^:private icon-ns? (set icon-namespaces))

(def ^:private marker ";; Generated by tyrell.icons.build/extract. Do not edit.")

(defn- ns->path [ns-sym]
  (str (-> (name ns-sym) (str/replace "-" "_") (str/replace "." "/")) ".cljc"))

(defn- read-all [text]
  (let [r (java.io.PushbackReader. (java.io.StringReader. text))
        eof (Object.)]
    (binding [*read-eval* false]
      (loop [acc []]
        (let [f (read {:eof eof :read-cond :allow :features #{:clj}} r)]
          (if (identical? f eof) acc (recur (conj acc f))))))))

;; --- Scanning ---------------------------------------------------------------

(defn- kondo-run!
  "clj-kondo is a build-time dependency of the :icons alias only, so the
   icon jars don't pull it onto every classpath."
  []
  (try
    (requiring-resolve 'clj-kondo.core/run!)
    (catch java.io.FileNotFoundException _
      (throw (ex-info (str "clj-kondo is not on the classpath. Add "
                           "clj-kondo/clj-kondo {:mvn/version \"2026.08.04\"} "
                           "to the alias that runs this.")
                      {})))))

(defn- usages
  "Icon vars the JVM side of :paths uses: #{[ns-sym name-sym]}. clj-kondo
   resolves aliases, :refer, require calls and .cljc branches; strings,
   comments and quoted data don't count. :cljs usages are dropped: the JVM
   never loads them."
  [paths out]
  (let [out-path (.getCanonicalPath (io/file out))
        result ((kondo-run!) {:lint paths
                              :skip-lint true
                              :config {:output {:canonical-paths true}
                                       :analysis {:var-usages true}}})]
    (into #{}
          (keep (fn [{:keys [to name lang filename]}]
                  (when (and (icon-ns? to)
                             (not= :cljs lang)
                             (not (str/starts-with? (str filename) out-path)))
                    [to name])))
          (get-in result [:analysis :var-usages]))))

;; --- Icon sets --------------------------------------------------------------

(defn- load-set
  "{:ns-form … :defs {name value}} from the full set on the classpath.
   Skips trimmed copies written by this tool."
  [ns-sym]
  (let [urls (enumeration-seq (.getResources (.getContextClassLoader (Thread/currentThread))
                                             (ns->path ns-sym)))
        text (some #(let [t (slurp %)] (when-not (str/starts-with? t marker) t)) urls)]
    (when-not text
      (throw (ex-info (str "Icon set " ns-sym " is not on the classpath. "
                           "Add dev.gersak/tyrell-icons to the alias that runs this.")
                      {:ns ns-sym})))
    (let [[ns-form & defs] (read-all text)]
      {:ns-form ns-form
       :defs (into {} (for [[_ n v] defs] [n v]))})))

(defn- resolve-svg
  "Follow (def old-name new-name) aliases to the SVG string."
  [defs n]
  (loop [v (get defs n) seen #{}]
    (if (and (symbol? v) (not (seen v)))
      (recur (get defs v) (conj seen v))
      (when (string? v) v))))

(defn- write-ns! [out ns-form icons]
  (let [f (io/file out (ns->path (second ns-form)))]
    (io/make-parents f)
    (binding [*print-length* nil *print-level* nil]
      (spit f (str marker "\n"
                   (pr-str ns-form) "\n"
                   (apply str (for [[n svg] icons]
                                (str "\n(def " n " " (pr-str svg) ")\n"))))))
    f))

(defn- write-svgs! [svg-dir ns-sym icons]
  (let [dir (-> (name ns-sym) (str/replace #"^tyrell\." "") (str/replace "." "/"))]
    (doseq [[n svg] icons
            :let [f (io/file svg-dir dir (str n ".svg"))]]
      (io/make-parents f)
      (spit f svg))))

;; --- Registration script ------------------------------------------------------

(defn- js-string [s]
  ;; pr-str escapes \\ \" and control chars the way JSON and JS expect
  (pr-str (str s)))

(defn- write-js!
  "A classic script (works with plain <script defer>) that registers the
   map with window.tyIcons once <ty-icon> is defined."
  [js-out registry]
  (let [f (io/file js-out)
        entries (for [[k svg] (sort-by (comp name key) registry)]
                  (str "  " (js-string (name k)) ": "
                       (js-string (str/replace svg #"^<\?xml[^>]*\?>\s*" ""))))]
    (io/make-parents f)
    (spit f (str "// Generated by tyrell.icons.build/extract. Do not edit.\n"
                 "(function () {\n"
                 "var icons = {\n" (str/join ",\n" entries) "\n};\n"
                 "function register() { window.tyIcons.register(icons); }\n"
                 "if (window.tyIcons) register();\n"
                 "else customElements.whenDefined('ty-icon').then(register);\n"
                 "})();\n"))
    (println (format "%-26s %3d icon%s  %6.1f KB  → %s"
                     "registration script" (count registry) (if (= 1 (count registry)) " " "s")
                     (/ (.length f) 1024.0) (.getPath f)))))

(defn- load-registry [sym]
  (let [v (requiring-resolve (symbol sym))
        m (some-> v deref)]
    (when-not (and (map? m) (every? string? (vals m)))
      (throw (ex-info (str sym " should hold a map of name -> SVG string.") {:registry sym})))
    m))

(defn extract
  "Scan :paths, write the referenced icons to :out. See the ns docstring."
  [{:keys [paths out include svg-dir registry js-out]
    :or {paths ["src"] out "gen-icons"}}]
  (when (and js-out (not registry))
    (throw (ex-info ":js-out needs :registry, the var with your name -> SVG map." {})))
  (let [paths (map str paths)
        out (str out)
        refs (into (usages paths out)
                   (for [q include
                         :let [q (symbol q)
                               lib (some-> (namespace q) symbol)]
                         :when (icon-ns? lib)]
                     [lib (symbol (name q))]))
        by-ns (group-by first refs)
        missing (atom [])]
    ;; Namespaces no longer used would otherwise linger as stale copies.
    (doseq [ns-sym icon-namespaces
            :when (not (contains? by-ns ns-sym))
            :let [f (io/file out (ns->path ns-sym))]
            :when (and (.exists f) (str/starts-with? (slurp f) marker))]
      (io/delete-file f))
    (doseq [[ns-sym pairs] (sort-by (comp str key) by-ns)
            :let [{:keys [ns-form defs]} (load-set ns-sym)
                  icons (into (sorted-map)
                              (keep (fn [[_ n]]
                                      (if-let [svg (resolve-svg defs n)]
                                        [n svg]
                                        (do (swap! missing conj (symbol (str ns-sym) (str n))) nil))))
                              pairs)]
            :when (seq icons)]
      (let [f (write-ns! out ns-form icons)]
        (when svg-dir (write-svgs! svg-dir ns-sym icons))
        (println (format "%-26s %3d icon%s  %6.1f KB  → %s"
                         ns-sym (count icons) (if (= 1 (count icons)) " " "s")
                         (/ (.length f) 1024.0) (.getPath f)))))
    (when (seq @missing)
      (println "\nNot found (typo, or not an icon):")
      (doseq [m (sort-by str @missing)] (println " " m)))
    (when js-out
      (write-js! js-out (load-registry registry)))
    (when (empty? by-ns)
      (println "No icon references found in" (str/join ", " paths)))))
